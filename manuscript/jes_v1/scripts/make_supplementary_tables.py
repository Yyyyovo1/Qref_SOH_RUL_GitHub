wb = openpyxl.load_workbook(ROOT / "supplementary/original/Supplementary_Tables_S1-S9.xlsx")

def add(name, caption, df, source):
    ws = wb.create_sheet(name)
    ws["A1"] = caption
    ws["A1"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(6, len(df.columns)))
    ws.row_dimensions[1].height = 60
    ws.cell(row=3, column=1)  # row 2 left blank as in S1-S9
    for j, c in enumerate(df.columns, 1):
        ws.cell(row=3, column=j, value=c).font = Font(bold=True)
    for i, row in enumerate(df.itertuples(index=False), 4):
        for j, v in enumerate(row, 1):
            ws.cell(row=i, column=j, value=(None if pd.isna(v) else (('TRUE' if v else 'FALSE') if isinstance(v, (bool,)) or type(v).__name__ == 'bool_' else (float(v) if isinstance(v, float) else v))))
    ws.cell(row=len(df) + 5, column=1, value="Source: " + source).font = Font(italic=True)
    ws.freeze_panes = "A4"
    for j, c in enumerate(df.columns, 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(j)].width = min(40, max(10, len(str(c)) + 2))

